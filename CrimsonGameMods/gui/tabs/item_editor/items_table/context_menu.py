class ItemTableContextMenu(QMenu):
    instance: Self | None = None

    def __init__(self, parent, **kwargs):
        super().__init__(parent, **kwargs)

    @classmethod
    def open(cls, parent, position, blocking=True):
        if cls.instance is None:
            cls.instance = cls(parent, toolTipsVisible=True)

        menu = cls.instance
        menu.clear()
        menu.addAction(QAction("hello darling", menu))

        return menu.exec(position) if blocking else menu.popup(position)
